type Packet struct {
	ID   uint16
	Data []byte
}

func (p Packet) String() string {
	return fmt.Sprintf("0x%04X len=%d", p.ID, len(p.Data))
}

func ID(data []byte) uint16 {
	if len(data) < 2 {
		return 0
	}
	return binary.LittleEndian.Uint16(data[:2])
}

